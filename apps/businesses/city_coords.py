_DIACRITIC_MAP = str.maketrans('čćžšđ', 'cczsd')


def fold_city_name(name: str) -> str:
    """Skini razmake, malo slovo, skini bosanske dijakritike (č/ć/ž/š/đ) radi tolerantnog poređenja gradova."""
    return name.strip().lower().translate(_DIACRITIC_MAP)


_CITY_COORDS_FOLDED = {fold_city_name(name): coords for name, coords in CITY_COORDS.items()}


def lookup_city_coords(city_name: str):
    """Dijakritika/case-neosjetljivo pretraživanje CITY_COORDS (npr. 'Bihac' ili 'sarajevo' i dalje pogađaju)."""
    if not city_name:
        return (None, None)
    coords = _CITY_COORDS_FOLDED.get(fold_city_name(city_name))
    return coords if coords else (None, None)
